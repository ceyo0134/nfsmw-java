#!/usr/bin/env python3
"""Lists every native method of the M3G Java classes (the contract a JS/WebGL M3G must implement)
and writes web/m3g-natives.js: a tracer that logs each native that gets called, so the
implementation can be done in the order the game actually needs it."""
import re, glob, json, os
root = os.path.join(os.path.dirname(__file__), "..", "..")
rx = re.compile(r'((?:\w+\s+)*?)native\s+([\w\[\]<>]+)\s+(\w+)\s*\(([^)]*)\)', re.S)
out = []
for f in sorted(glob.glob(os.path.join(root, "src/main/java/javax/microedition/m3g/*.java"))):
    cls = os.path.basename(f)[:-5]
    src = open(f).read()
    src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
    src = re.sub(r'//[^\n]*', '', src)
    for m in rx.finditer(src):
        mods, ret, name, params = m.groups()
        params = " ".join(params.split())
        out.append({"cls": cls, "name": name, "static": "static" in mods, "ret": ret, "params": params})
names = {}
for o in out: names.setdefault((o["cls"], o["name"]), 0); names[(o["cls"], o["name"])] += 1
json.dump(out, open(os.path.join(root, "web", "m3g-natives.json"), "w"), indent=1)
lines = ["// GENERATED by tools/gen_natives.py - %d native methods" % len(out),
         "// Each entry traces its first call; replace bodies with real WebGL-backed code.",
         "export const natives = {};", "const seen = new Set();",
         "function trace(n, a) { if (!seen.has(n)) { seen.add(n); console.warn('[m3g native not implemented]', n, a); } }"]
for o in out:
    jn = "Java_javax_microedition_m3g_%s_%s" % (o["cls"], o["name"].replace("_", "_1"))
    lines.append("natives.%s = async function(lib, ...a) { trace('%s.%s(%s)', a); return 0; };" % (jn, o["cls"], o["name"], o["params"].replace("'", "")))
open(os.path.join(root, "web", "m3g-natives.js"), "w").write("\n".join(lines) + "\n")
print(len(out), "natives in", len(set(o["cls"] for o in out)), "classes")
